import assert from 'node:assert/strict';
import {test} from 'node:test';
import {DatabaseSync} from 'node:sqlite';
import {readFileSync} from 'node:fs';
import {apply,initial,route} from './core.js';
const config={type:'settings',id:'config-00001',price:2500,capacity:1};
const start={type:'start',id:'start-000001',age:'3–5',method:'QR',expected:2500};
test('ingreso, cupo, reintentos, renovación, llamado, salida y anulación',()=>{
  let state=apply(initial(),config,1);
  state=apply(state,start,1000);
  assert.equal(state.turns[0].end,901000);
  assert.equal(state.turns[0].number,1);
  assert.equal(apply(state,start,1400),state);
  assert.throws(()=>apply(state,{...start,id:'start-000002'},2000),/Cupo/);
  const turn=start.id;
  const renew={type:'renew',id:'renew-000001',turn,previousEnd:901000,method:'QR',expected:2500};
  state=apply(state,renew,2000);
  assert.equal(state.turns[0].end,1801000);
  assert.equal(state.payments.length,2);
  assert.throws(()=>apply(state,{...renew,id:'renew-000002'},2200),/ya cambió/);
  state=apply(state,{type:'call',id:'call-0000001',turn},1801000);
  state=apply(state,{type:'close',id:'close-000001',turn},1802000);
  assert.equal(state.turns[0].status,'closed');
  state=apply(state,{type:'void',id:'void-0000001',turn,reason:'Devolución'},1803000);
  assert.ok(state.payments.every(p=>p.voided===1803000));
});
test('operaciones simultáneas observan el mismo cupo y estado confirmado',async()=>{
  const sql=new DatabaseSync(':memory:');
  sql.exec(readFileSync('drizzle/0001_state.sql','utf8'));
  const db={prepare(text){
    const statement=sql.prepare(text);
    const bind=(...params)=>({run:()=>({meta:statement.run(...params)}),first:()=>statement.get(...params)});
    return {...bind(),bind};
  }};
  const send=action=>route(new Request('http://localhost/api/state',action?{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(action)}:{}),db,{});
  assert.equal((await send(config)).status,200);
  const results=await Promise.all([send(start),send({...start,id:'start-000002'})]);
  assert.deepEqual(results.map(r=>r.status).sort(),[200,409]);
  const data=await (await send()).json();
  assert.equal(data.state.turns.length,1);
  assert.equal(data.state.payments.length,1);
  assert.equal((await send(start)).status,200);
  assert.equal((await (await send()).json()).state.payments.length,1);
  sql.close();
});
test('precio personalizado, cortesía con propina y reintento',()=>{
  let state=apply(initial(),{...config,capacity:3},1);
  const paid={...start,price:1800,tip:200,expected:2000};
  state=apply(state,paid,1000);
  assert.equal(state.payments[0].amount,2000);
  assert.equal(state.payments[0].tip,200);
  assert.equal(state.settings.price,2500);
  assert.equal(apply(state,paid,1200),state);
  const courtesy={...start,id:'courtesy-00001',method:'Cortesía',price:0,tip:300,expected:300};
  assert.throws(()=>apply(state,courtesy,1500),/cómo se recibió/);
  assert.throws(()=>apply(state,{...courtesy,price:100},1500),/precio válido/);
  state=apply(state,{...courtesy,tipMethod:'Transferencia'},1500);
  assert.equal(state.payments[1].amount,300);
  assert.equal(state.payments[1].tipMethod,'Transferencia');
  assert.equal(state.payments[1].method,'Cortesía');
  const renewed=apply(state,{type:'renew',id:'renew-000001',turn:start.id,previousEnd:901000,method:'Efectivo',price:1600,tip:100,expected:1700},2000);
  assert.equal(renewed.payments[2].amount,1700);
});
